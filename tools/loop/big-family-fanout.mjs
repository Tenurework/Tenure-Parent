const STANDARD = `
═══ THE STANDARD ═══

MUTATION PROOF OR IT DID NOT HAPPEN. For each behaviour you claim: apply a mutation that should
break it, RUN the test, CONFIRM IT FAILS, restore, confirm green. Report the mutation and both
results verbatim. Mutate ONE thing at a time and use a literal value — two mutations at once can
mask each other, which fooled an agent here this week, and a hit-area test was found passing
against a 16px control because its probe accepted the wrapping element.

DO NOT CALIBRATE A TEST TO THIS MACHINE. Two specs went green here and red in CI this week because
they asserted absolute pixels that depend on content and font metrics. If you assert a measured
number, assert something the TOKENS or the LOGIC fix — not something the data can move. A row
count is data. A line-height times a font size is arithmetic.

BUILD ON WHAT EXISTS. Grep before you write. \`apps/web/src/lib/\` and \`packages/\` are large and the
conventions are strong; a second implementation of something that exists is a defect. The
repository already carries a note about what having two parsers cost.

WHAT "REAL" MEANS. No stub, no TODO, no function returning a constant so a test can pass, no
hardcoded demo data. If a value cannot be computed the code must SAY it could not — "we looked and
found nothing" and "we could not look" are different answers and collapsing them is the bug this
codebase most often finds.

SCOPE. Close TWO to SIX properly rather than fifteen shallowly. A refuter re-runs every mutation
and reads the requirement's own sentence; a claim it overturns costs more than one you never made.
`

const CLOSE_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['slice', 'results'],
  properties: {
    slice: { type: 'string' },
    results: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'status', 'requirement', 'summary', 'mutation_proof', 'ledger_row'],
        properties: {
          id: { type: 'string' },
          status: {
            type: 'string',
            enum: ['PASS', 'FAIL', 'BLOCKED_EXTERNAL', 'NEEDS_SCHEMA', 'NOT_APPLICABLE'],
          },
          requirement: { type: 'string' },
          summary: { type: 'string' },
          mutation_proof: { type: 'string' },
          ledger_row: { type: 'string' },
        },
      },
    },
    ledger_file: { type: 'string' },
    files_changed: { type: 'array', items: { type: 'string' } },
    shared_files_touched: { type: 'array', items: { type: 'string' } },
    considered_and_rejected: { type: 'string' },
    needed_a_build: { type: 'boolean' },
  },
}

const VERDICT_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['slice', 'verdicts'],
  properties: {
    slice: { type: 'string' },
    verdicts: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['id', 'refuted', 'reason'],
        properties: {
          id: { type: 'string' },
          refuted: { type: 'boolean' },
          reason: { type: 'string' },
        },
      },
    },
    tree_left_clean: { type: 'boolean' },
  },
}

phase('Close')
log(`${SLICES.length} slices across GE, IER, EXT, PAY, SIMON and STUDIO — 2005 open between them`)

const outcomes = await pipeline(
  SLICES,

  (slice) =>
    agent(
      `${RULES}${HOW_IT_COUNTS}${STANDARD}

YOUR SLICE IS ${slice.key}: family ${slice.family}, requirement bands ${slice.bands}, roughly
${slice.open} of them not recorded as passing.

STAY INSIDE YOUR BANDS. Other agents hold the other bands of ${slice.family} and every other
family, all at the same time. A requirement outside ${slice.bands} is not yours even when it is
tempting and adjacent — closing it duplicates another agent's work and both of you lose.

ELEVEN OTHER AGENTS ARE EDITING THIS TREE RIGHT NOW. Therefore:
  · Prefer ADDING a file over editing a shared one. Anything under \`apps/web/src/lib/\`,
    \`packages/\`, \`tools/\`, \`apps/system-studio/src/app/globals.css\` or a shared test is plausibly
    somebody else's subject this hour.
  · List every shared file you touched in \`shared_files_touched\`. That list is how the
    orchestrator finds collisions, and an unreported one is how a wave loses work.
  · A file you did not expect to have changed is another agent mid-flight, not damage. Do not
    "fix" it and do not revert it.
  · Never edit any \`docs/implementation/*-ledger.md\` — you RETURN rows, you do not write them.

WHAT TO DO:
  1. Read your ids out of the registry, then read each requirement's own sentence in its authority.
  2. Read your family's ledger for what has already been tried and refused.
  3. Pick TWO to SIX you can genuinely close now, preferring ones provable without a build.
  4. Close them with real code, real tests, mutation-proven, wired to a caller.
  5. Return a \`ledger_row\` for each — and set \`ledger_file\` to your family's ledger filename so
     the orchestrator knows where they go.
  6. Put what you considered and rejected in \`considered_and_rejected\`, with the blocker for each.
     For a family this size that list is the most useful thing you produce after the code: it tells
     the next wave where the walls actually are.

If ${slice.family} turns out to need infrastructure that does not exist — a service, a schema, an
external credential — then say so precisely, with FAIL or NEEDS_SCHEMA rows naming the blocker.
That is a real result. Two thin passes and a silent 150 are not.`,
      { label: `close:${slice.key}`, phase: 'Close', schema: CLOSE_SCHEMA, effort: 'high' },
    ),

  (closed, slice) => {
    if (!closed) return null
    const claims = (closed.results || []).filter((r) => r.status === 'PASS')
    if (claims.length === 0) return { slice: slice.key, closed, verdict: { slice: slice.key, verdicts: [] } }

    return agent(
      `${RULES}

You are a REFUTER for slice ${slice.key} (family ${slice.family}). Another agent claims it closed
these ${claims.length}. Default refuted=true; set false ONLY for what you verify YOURSELF by
running it.

${claims
  .map(
    (r) =>
      `- ${r.id}\n  requirement: ${r.requirement}\n  claim: ${r.summary}\n  mutation claimed: ${r.mutation_proof}`,
  )
  .join('\n\n')}

CHECK IN THIS ORDER and stop at the first thing that is false:

 1. DOES THE REQUIREMENT'S OWN SENTENCE SAY WHAT THE CLAIM SAYS IT SAYS? Open the authority and
    read it. This is where claims die here — not on broken code but on a requirement closed against
    a narrower reading of itself. Last wave that was 14 of 18 overturned: "locate EVERY hard-coded
    assumption" closed by a scan that missed the pilot's own role vocabulary; "build twenty-two
    primitives" closed on eleven. If the claim closes PART of a requirement, it is FAIL.
 2. RE-RUN EVERY MUTATION. Apply, run, watch it fail, restore, confirm green. A mutation that
    SURVIVES means the test does not test what was claimed — the highest-value thing you will find.
    One at a time; two together can mask each other.
 3. IS THE CODE REACHED? grep for the caller. "No surface imports it yet" is FAIL.
 4. IS IT REAL? No stub, no constant return, no hardcoded demo value, no swallowed error. Check
    specifically that an uncomputable value is reported as unknown rather than as zero or empty.
 5. WOULD THE TEST SURVIVE A DIFFERENT MACHINE? A number calibrated on this host's fonts, data or
    row heights is a red CI for everybody else. Two specs did exactly that here this week.
 6. DOES THE RETURNED LEDGER ROW MATCH THE WORK? A row citing evidence that does not reproduce is
    worse than no row.

Edit files ONLY to apply and restore mutations, and only inside ${slice.key}'s area. Other agents
are working in this tree. Set tree_left_clean to whether you left it exactly as you found it.`,
      { label: `refute:${slice.key}`, phase: 'Refute', schema: VERDICT_SCHEMA, effort: 'high' },
    ).then((verdict) => ({ slice: slice.key, closed, verdict }))
  },
)

/* ── tally, and hand the rows back for the orchestrator to write ──────────── */

const rows = []
for (const o of outcomes.filter(Boolean)) {
  const closed = o.closed
  const verdicts = new Map(((o.verdict || {}).verdicts || []).map((v) => [v.id, v]))
  for (const r of closed.results || []) {
    const v = verdicts.get(r.id)
    rows.push({
      ...r,
      slice: closed.slice,
      ledger_file: closed.ledger_file,
      confirmed: r.status === 'PASS' && v?.refuted === false,
      refutedWhy: v?.reason,
    })
  }
}

const confirmed = rows.filter((r) => r.confirmed)
const overturned = rows.filter((r) => r.status === 'PASS' && !r.confirmed)
const recorded = rows.filter((r) => r.status !== 'PASS')

log(`confirmed ${confirmed.length} · overturned ${overturned.length} · recorded ${recorded.length}`)

return {
  program: 'big-family-fanout',
  confirmed,
  overturned,
  recorded,
  shared_files: outcomes.filter(Boolean).flatMap((o) => o.closed.shared_files_touched || []),
  files: outcomes.filter(Boolean).flatMap((o) => o.closed.files_changed || []),
  builders: outcomes.filter(Boolean).filter((o) => o.closed.needed_a_build).length,
  walls: outcomes
    .filter(Boolean)
    .map((o) => ({ slice: o.closed.slice, rejected: o.closed.considered_and_rejected })),
}
