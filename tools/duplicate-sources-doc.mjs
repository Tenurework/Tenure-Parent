#!/usr/bin/env node
/**
 * Renders `docs/migrations/duplicate-sources.json` into the readable plan.
 *
 *   node tools/duplicate-sources-doc.mjs           # write
 *   node tools/duplicate-sources-doc.mjs --check   # fail if stale
 *
 * GE-020-005 is about facts stored in two places drifting apart. Writing the
 * plan twice — once as data for the guard, once as prose for a human — would be
 * the same mistake in the deliverable itself: the JSON would say `Budget` is
 * deprecated and the Markdown would still say consolidate, and whichever a
 * reader opened would be the one they believed.
 *
 * So there is one source. The guard reads the JSON; a person reads this.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const SRC = "docs/migrations/duplicate-sources.json"
const OUT = "docs/migrations/DUPLICATE-SOURCES.md"

const registry = JSON.parse(fs.readFileSync(path.join(ROOT, SRC), "utf8"))

const VERDICTS = {
  LINK_NOT_MERGE: "Link them. Do not merge.",
  KEEP_BOTH_DIFFERENT_DOMAINS: "Keep both — they answer different questions.",
  TWO_SYSTEMS_UNIFY_LATER: "Two systems. Unify in the authorization engine, not in a migration.",
  ONE_ENGINE_THREE_IMPLEMENTATIONS: "One engine, three implementations. Stop adding more.",
  THREE_TRAILS_ONE_UNWIRED: "Three trails. Two are complementary; one is not connected.",
  DROP_ONE_STACK_AND_DECIDE_ONE_FIELD: "Drop the dead stack. Decide the contested column first.",
}

const list = (items) => items.map((i) => `- ${i}`).join("\n")

function renderFamily(f) {
  const rows = f.sources
    .map((s) => `| \`${s.model}\` | ${s.role} | ${s.holds} | ${s.writers.length} |`)
    .join("\n")

  let out = `
## ${f.fact} — ${f.question}

**${VERDICTS[f.verdict] ?? f.verdict}**

${f.reason}

| source | role | holds | writers |
|---|---|---|---|
${rows}
`

  if (f.contestedField) {
    const c = f.contestedField
    out += `
### The contested column: \`${c.column}\`

${c.problem}

**Measured.** ${c.measured}

**Not decided here.** ${c.whyNotFixedHere}

${c.options.map((o) => `- ${o}`).join("\n")}
`
  }

  out += `
### Plan

${list(f.plan)}

### Before anything is dropped

${list(f.beforeAnyDrop)}
`
  return out
}

const generated = `<!--
  GENERATED by tools/duplicate-sources-doc.mjs from ${SRC}.
  Edit the JSON, not this file. \`npm run generate\` rewrites it and CI checks it.
-->

# Duplicate sources of the same fact

${registry.item} — ${registry.what}

Six facts are stored in more than one place. Only one of the six is a
straightforward duplicate where something can be dropped; the other five look
like duplication and are not, which is the reason this file exists. Deleting a
table because it resembles another one is how the answer to "who ran this club
last year" disappears.

**How this stays true.** ${registry.howVerified}

**What counts as a writer.** \`${registry.writerDetection.pattern}\`, searched in
${registry.writerDetection.searched.map((s) => `\`${s}\``).join(", ")}, excluding
${registry.writerDetection.excluded}.

> ${registry.writerDetection.note}

**How strictly each role is held.**

${Object.entries(registry.strictness)
  .map(([role, rule]) => `- \`${role}\` — ${rule}`)
  .join("\n")}
${registry.families.map(renderFamily).join("\n---\n")}
---

## Running the measurement

\`\`\`bash
DATABASE_URL=... node apps/web/scripts/duplicate-source-report.mjs
\`\`\`

Read-only, and it exits 0 whether or not it finds something. A blocker is
information for a human about to sign a migration, not a broken build — failing
CI because the pilot has real data in it would train everyone to pass \`--force\`.
`

if (process.argv.includes("--check")) {
  const current = fs.existsSync(path.join(ROOT, OUT)) ? fs.readFileSync(path.join(ROOT, OUT), "utf8") : ""
  if (current !== generated) {
    console.error(`::error::${OUT} is stale. Run: node tools/duplicate-sources-doc.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is up to date.`)
} else {
  fs.writeFileSync(path.join(ROOT, OUT), generated)
  console.log(`Wrote ${OUT} — ${registry.families.length} families.`)
}
